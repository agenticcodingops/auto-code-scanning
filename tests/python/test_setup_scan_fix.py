"""Tests for the cross-platform setup-scan-fix scripts."""

import os
import json
import shutil
import subprocess
import sys
from pathlib import Path

import setup_scan_fix
import pytest


def test_python_setup_vendors_schemas(tmp_path: Path, monkeypatch):
    """The Python setup copies every schema beside the copied validator."""
    monkeypatch.setattr(setup_scan_fix, "have", lambda _command: False)
    monkeypatch.setattr(setup_scan_fix.subprocess, "run", lambda *args, **kwargs: None)

    assert setup_scan_fix.main(["setup-scan-fix.py", "--repo-path", str(tmp_path)]) == 0

    source_names = {path.name for path in (setup_scan_fix.PLATFORM_ROOT / "schemas").iterdir()}
    copied_names = {path.name for path in (tmp_path / "schemas").iterdir()}
    assert copied_names == source_names
    assert (tmp_path / "scripts/validate-scan-config.py").is_file()
    for name in ('scan.py', 'scan_policy.py', 'scan_reports.py', 'validate-suppressions.py',
                 'create-baseline.ps1', 'finalize_baseline.py'):
        assert (tmp_path / 'scripts' / name).is_file()
        assert name in (setup_scan_fix.PLATFORM_ROOT / 'scripts/setup-scan-fix.ps1').read_text()


def test_copied_validator_uses_vendored_schema(tmp_path: Path, repo_root: Path):
    """The copied validator finds its schema and enforces it in strict mode."""
    setup = subprocess.run(
        [
            sys.executable,
            str(repo_root / "scripts/setup-scan-fix.py"),
            "--repo-path",
            str(tmp_path),
        ],
        capture_output=True,
        text=True,
        check=False,
        timeout=300,
    )
    assert setup.returncode == 0, setup.stdout + setup.stderr

    validator = tmp_path / "scripts/validate-scan-config.py"
    environment = {**os.environ, "STRICT": "1"}
    valid = subprocess.run(
        [sys.executable, str(validator), str(tmp_path / "scan-config.yaml")],
        cwd=tmp_path,
        env=environment,
        capture_output=True,
        text=True,
        check=False,
        timeout=60,
    )
    assert valid.returncode == 0, valid.stdout + valid.stderr

    invalid_config = tmp_path / "invalid-scan-config.yaml"
    invalid_config.write_text('schema_version: "1.0"\nlanguages: []\n', encoding="utf-8")
    invalid = subprocess.run(
        [sys.executable, str(validator), str(invalid_config)],
        cwd=tmp_path,
        env=environment,
        capture_output=True,
        text=True,
        check=False,
        timeout=60,
    )
    assert invalid.returncode == 1, invalid.stdout + invalid.stderr


def test_powershell_setup_vendors_schemas(repo_root: Path):
    """The PowerShell twin also copies the schema directory."""
    powershell_setup = (repo_root / "scripts/setup-scan-fix.ps1").read_text()

    assert 'Join-Path $PlatformRoot "schemas"' in powershell_setup


@pytest.mark.parametrize('implementation', ['py', 'ps1'])
@pytest.mark.parametrize('install_fails,adapter_refuses', [(False, False), (True, False),
                                                          (False, True), (True, True)])
def test_setup_reports_install_failures_and_finishes_remaining_steps(
        tmp_path, repo_root, implementation, install_fails, adapter_refuses):
    """Exercise both setup entrypoints, including the adapter's real refusal."""
    pwsh = shutil.which('pwsh')
    if implementation == 'ps1' and not pwsh:
        pytest.skip('PowerShell unavailable')
    platform = tmp_path / 'platform'
    for folder in ('scripts', 'hooks', 'schemas', 'templates'):
        shutil.copytree(repo_root / folder, platform / folder,
                        ignore=shutil.ignore_patterns('__pycache__'))
    # Verification and external account commands are deterministic local stubs.
    (platform / 'scripts/verify-scanning.ps1').write_text("Write-Output 'VERIFY_REACHED'\nexit 0\n")
    consumer = tmp_path / 'consumer'
    consumer.mkdir()
    env = {key: value for key, value in os.environ.items() if not key.startswith('GIT_')}
    subprocess.run(['git', 'init', '-q'], cwd=consumer, env=env, check=True)
    subprocess.run(['git', 'config', 'core.hooksPath', '.git/hooks'],
                   cwd=consumer, env=env, check=True)
    existing = ('#!/bin/sh\n# custom pre-push hook\n' if adapter_refuses else
                '#!/bin/sh\n# File generated by pre-commit\n# end templated\n')
    push_hook = consumer / '.git/hooks/pre-push'
    push_hook.write_text(existing)
    bin_dir = tmp_path / 'bin'
    bin_dir.mkdir()
    for name, source in {
        'pre-commit': 'import os,sys\n'
                      'code=int(os.environ["INSTALL_EXIT"])\n'
                      'if code: print("pre-commit install refused", file=sys.stderr)\n'
                      'sys.exit(code)\n',
        'gh': 'import json,os,pathlib,sys\n'
              'with open(os.environ["GH_TRACE"], "a") as f: f.write(json.dumps(sys.argv[1:])+"\\n")\n'
              'if sys.argv[1:3] == ["secret", "list"]: print("[]")\n',
    }.items():
        script = bin_dir / f'{name}.py'
        script.write_text(source)
    trace = tmp_path / 'gh-trace'
    env.update(PATH=str(bin_dir) + os.pathsep + env['PATH'], INSTALL_EXIT='7' if install_fails else '0',
               GH_TRACE=str(trace))
    if implementation == 'py':
        # Resolve only the two external tools to stubs. Keep the actual adapter,
        # rendering, vendoring, and verification as subprocesses/file operations.
        bootstrap = tmp_path / 'setup.py'
        bootstrap.write_text(
            'import os,runpy,shutil,subprocess,sys\n'
            'run,which=subprocess.run,shutil.which\n'
            'stubs={name:os.path.join(sys.argv[1],name+".py") for name in ("pre-commit","gh")}\n'
            'subprocess.run=lambda cmd,**kw: run([sys.executable,stubs[cmd[0]],*cmd[1:]] '
            'if cmd[0] in stubs else cmd,**kw)\n'
            'shutil.which=lambda cmd: stubs.get(cmd) or which(cmd)\n'
            'sys.argv=sys.argv[2:]\n'
            'sys.path.insert(0,os.path.dirname(sys.argv[0]))\n'
            'runpy.run_path(sys.argv[0],run_name="__main__")\n')
        command = [sys.executable, str(bootstrap), str(bin_dir), str(platform / 'scripts/setup-scan-fix.py'),
                   '--repo-path', str(consumer), '--hooks-runner', 'pre-commit', '--enable-fix-loop']
    else:
        bootstrap = tmp_path / 'setup.ps1'
        bootstrap.write_text(
            'function pre-commit { & $env:STUB_PY "$env:STUB_BIN/pre-commit.py" @args }\n'
            'function gh { & $env:STUB_PY "$env:STUB_BIN/gh.py" @args }\n'
            '$setupArgs = @($args | Select-Object -Skip 1)\n'
            '& $args[0] @setupArgs\nexit $LASTEXITCODE\n')
        env.update(STUB_PY=sys.executable, STUB_BIN=str(bin_dir))
        command = [pwsh, '-NoProfile', '-File', str(bootstrap), str(platform / 'scripts/setup-scan-fix.ps1'),
                   '-RepoPath', str(consumer), '-HooksRunner', 'pre-commit', '-EnableFixLoop']
    result = subprocess.run(command, cwd=consumer, env=env, text=True, capture_output=True, timeout=90)
    output = result.stdout + result.stderr
    assert result.returncode == int(install_fails or adapter_refuses), output
    assert ('FAILED: pre-commit hook installation' in output) == install_fails, output
    assert ('FAILED: push transaction adapter installation' in output) == adapter_refuses, output
    assert 'Traceback' not in output
    assert (consumer / '.claude/settings.json').is_file(), output
    assert (consumer / '.github/workflows/code-security-scan.yml').is_file()
    assert (consumer / '.github/workflows/autonomous-fix.yml').is_file()
    calls = [json.loads(line) for line in trace.read_text().splitlines()]
    assert [call[:2] for call in calls] == [['label', 'create'], ['label', 'create'], ['secret', 'list']]
    if pwsh:
        assert 'VERIFY_REACHED' in output
    if adapter_refuses:
        assert 'Refusing to replace an unrecognized pre-push hook' in output
        assert push_hook.read_text() == existing
    else:
        assert '# scan push transaction adapter' in push_hook.read_text()
    if install_fails or adapter_refuses:
        assert 'SETUP COMPLETED WITH ERRORS' in output
        assert 're-run setup' in output
    else:
        assert '=== SETUP COMPLETE ===' in output
